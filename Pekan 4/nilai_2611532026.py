# Buat program untuk nested if
# Nama variabel diatmbah 4 digit nim terakhir contoh: ipk_1234
# Program ini mengguanakan fungsi input()
# Program konversi nilai angka menjadi huruf

nilai_2026 = int(input("Inputkan nilai angka= "))

if nilai_2026 >= 81:
    print("A")
elif nilai_2026 >= 70:
    print("B")
elif nilai_2026 >= 60:
    print("C")
elif nilai_2026 >= 50:
    print("D")
else:
    print("E")